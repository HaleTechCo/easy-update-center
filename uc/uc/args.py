"""Arguments file for update-center2 batch mode, mirroring upstream site/generate.sh:110-130 (spec §6 step 6)."""

from __future__ import annotations

from typing import TYPE_CHECKING

from .errors import UcError

if TYPE_CHECKING:
    from pathlib import Path

    from .config import Settings
    from .model import Tiers


class ArgumentsError(UcError):
    """A setting cannot be written to update-center2's space-separated arguments file."""


def common_arguments(settings: Settings) -> list[str]:
    """Return the options every update site line starts with: signing material, connection check, id and UC_EXTRA_ARGS."""
    return [
        '--key',
        str(settings.signing_key_file),
        '--certificate',
        str(settings.signing_cert_file),
        '--root-certificate',
        str(settings.root_ca_file),
        '--connection-check-url',
        f'{settings.public_url}/uctest.json',
        '--id',
        settings.uc_id,
        *settings.extra_args,
    ]


def build_argument_lines(settings: Settings, staging: Path, tiers: Tiers) -> list[str]:
    """Return one arguments-file line per update site: each weekly and stable tier, experimental, then current.

    Raises ArgumentsError when a token is empty or contains whitespace, since update-center2 splits lines on spaces.
    """
    s = str(staging)
    sites: list[list[str]] = [
        *(['--limit-plugin-core-dependency', version, '--write-latest-core', '--write-timestamp', '--www-dir', f'{s}/dynamic-{version}'] for version in tiers.weekly),
        *(['--limit-plugin-core-dependency', version, '--write-latest-core', '--write-timestamp', '--www-dir', f'{s}/dynamic-stable-{version}', '--only-stable-core'] for version in tiers.stable),
        ['--www-dir', f'{s}/experimental', '--generate-recent-releases', '--with-experimental', '--latest-links-directory', f'{s}/experimental/latest'],
        [
            '--generate-release-history',
            '--generate-recent-releases',
            '--generate-plugin-versions',
            '--generate-plugin-documentation-urls',
            '--write-latest-core',
            '--write-timestamp',
            '--write-plugin-count',
            '--www-dir',
            f'{s}/current',
            '--download-links-directory',
            f'{s}/download',
            '--latest-links-directory',
            f'{s}/current/latest',
        ],
    ]
    lines = []
    for site in sites:
        tokens = [*common_arguments(settings), *site]
        bad = [t for t in tokens if not t or any(c.isspace() for c in t)]
        if bad:
            msg = f'update-center2 splits argument lines on spaces; these values cannot be used: {bad}'
            raise ArgumentsError(msg)
        lines.append(' '.join(tokens))
    return lines


def write_arguments_file(lines: list[str], path: Path) -> None:
    """Write the lines as an --arguments-file, behind a comment header."""
    path.write_text('# one update site per line (generated by uc)\n' + '\n'.join(lines) + '\n', encoding='utf-8')
