"""Unit tests for uc.args.

The update-center2 arguments file, one update site per line.
"""

import pytest

from uc.args import ArgumentsError, build_argument_lines, write_arguments_file
from uc.model import Tiers
from ucsupport import make_settings


def test_each_update_site_gets_its_argument_line(tmp_path, secrets_dir):
    settings = make_settings(tmp_path, secrets_dir, UC_EXTRA_ARGS='--max-plugins 20')
    staging = tmp_path / 'data' / 'releases' / 'R.staging'
    lines = build_argument_lines(settings, staging, Tiers(('2.540',), ('2.528.1',)))
    common = (
        f'--key {secrets_dir}/update-center.key '
        f'--certificate {secrets_dir}/update-center.cert '
        f'--root-certificate {secrets_dir}/root-ca.crt '
        '--connection-check-url https://uc.example.com/uctest.json '
        '--id default --max-plugins 20'
    )
    s = str(staging)
    assert lines == [
        (
            f'{common} --limit-plugin-core-dependency 2.540 --write-latest-core '
            f'--write-timestamp --www-dir {s}/dynamic-2.540'
        ),
        (
            f'{common} --limit-plugin-core-dependency 2.528.1 --write-latest-core '
            f'--write-timestamp --www-dir {s}/dynamic-stable-2.528.1 '
            '--only-stable-core'
        ),
        (
            f'{common} --www-dir {s}/experimental --generate-recent-releases '
            f'--with-experimental --latest-links-directory {s}/experimental/latest'
        ),
        (
            f'{common} --generate-release-history --generate-recent-releases '
            '--generate-plugin-versions --generate-plugin-documentation-urls '
            '--write-latest-core --write-timestamp --write-plugin-count '
            f'--www-dir {s}/current --download-links-directory {s}/download '
            f'--latest-links-directory {s}/current/latest'
        ),
    ]


def test_zero_tiers_build_experimental_and_current_only(tmp_path, secrets_dir):
    lines = build_argument_lines(
        make_settings(tmp_path, secrets_dir), tmp_path / 's', Tiers()
    )
    assert len(lines) == 2
    assert '--with-experimental' in lines[0]
    assert '--generate-plugin-versions' in lines[1]


def test_paths_with_spaces_are_rejected(tmp_path, secrets_dir):
    settings = make_settings(tmp_path, secrets_dir)
    with pytest.raises(ArgumentsError, match='splits argument lines on spaces'):
        build_argument_lines(settings, tmp_path / 'has space', Tiers())


def test_write_arguments_file(tmp_path):
    path = tmp_path / 'args.lst'
    write_arguments_file(['--a 1', '--b 2'], path)
    assert (
        path.read_text()
        == '# one update site per line (generated by uc)\n--a 1\n--b 2\n'
    )
